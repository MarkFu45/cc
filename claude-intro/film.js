function renderInner(t) {
  const [c, b] = E.buf('inner', W, H);
  const cam = E.camera({ x: CX, y: CY, zoom: camZ(40.6) * (1 + 0.02 * seg(t, K.reveal, K.collapse)) });
  drawStage(b, cam); cam.apply(b, 0); drawNumber(b, t); b.setTransform(1, 0, 0, 1, 0, 0); E.vignette(b, 0.52);
  return c;
}

function renderReveal(g, t) {
  const inner = renderInner(t);
  const cam = E.camera({ x: CX, y: CY, zoom: 1 });
  drawStage(g, cam);
  const p = seg(t, K.reveal, K.reveal + 0.55), q = back(p, 1.15);
  const full = { x: 0, y: 0, w: W, h: H };
  const pvWin = { x: PV.x, y: PV.y - 40, w: PV.w, h: PV.h + 40 };
  const cp = seg(t, K.collapse + 0.2, K.collapse + 0.45), cp2 = seg(t, K.collapse + 0.45, K.bar2);
  const srcA = seg(t, K.reveal + 0.3, K.reveal + 0.6), srcSlide = (1 - back(seg(t, K.reveal + 0.3, K.reveal + 0.7), 1.3)) * 120 + ei(seg(t, K.collapse, K.collapse + 0.3)) * 1100;
  if (srcA > 0) drawSource(g, t, srcA * (1 - seg(t, K.collapse + 0.15, K.collapse + 0.3)), srcSlide);
  drawTimeline(g, t, seg(t, K.reveal + 0.45, K.reveal + 0.85) * (1 - seg(t, K.collapse + 0.1, K.collapse + 0.3)));
  if (cp > 0) {
    const h = lerp(pvWin.h, BAR.h, ei(cp));
    const r0 = { x: pvWin.x, y: pvWin.y + (pvWin.h - h) / 2, w: pvWin.w, h };
    const tgt = { x: CX - BAR.w / 2, y: CY - BAR.h / 2, w: BAR.w, h: BAR.h };
    const r = lerpR(r0, { ...tgt, h }, eio(cp2));
    g.save();
    E.panel(g, r.x, r.y, r.w, r.h, { r: lerp(14, r.h / 2, cp), fill: PAL.surf2 });
    g.globalAlpha = 1 - seg(cp, 0.55, 1); rr(g, r.x, r.y, r.w, r.h, lerp(14, r.h / 2, cp)); g.clip();
    g.drawImage(inner, r.x, r.y - (PV.h - r.h) / 2 * 0, r.w, Math.max(r.h, 1));
    g.restore();
    if (cp2 > 0.6) E.caret(g, CX - BAR.w / 2 + 34, CY, 35, { on: 1, glow: 0.8, wr: 1 / 10, alpha: seg(cp2, 0.6, 1) });
  } else {
    const r = lerpR(full, PV, clamp(q, -0.05, 1.05));
    if (p > 0.15) {
      const wp = seg(p, 0.15, 0.6);
      const barH = 40 * wp;
      g.save(); g.globalAlpha = wp;
      E.windowBox(g, r.x, r.y - barH, r.w, r.h + barH, { title: 'index.html — 预览', app: 3, bar: Math.max(1, barH) });
      g.restore();
    }
    g.save(); rr(g, r.x, r.y, r.w, r.h, lerp(0, 10, p)); g.clip(); g.drawImage(inner, r.x, r.y, r.w, r.h); g.restore();
  }
  g.setTransform(1, 0, 0, 1, 0, 0);
  E.vignette(g, 0.45);
}

function drawSubs(g, t) {
  for (const s of SUBS) {
    if (!s.burn || t < s.t0 || t >= s.t1) continue;
    const a = Math.min(seg(t, s.t0, s.t0 + 0.16), 1 - seg(t, s.t1 - 0.12, s.t1));
    E.toast(g, s.text, a, { dense: t < K.freeze ? 1 : 0 });
  }
}

// ───────────── events for the mixer ─────────────
export function buildEvents() {
  const ev = [];
  for (const it of ITEMS) {
    ev.push({ t: it.s, type: 'spawn', kind: it.kind, i: it.i, pan: (it.x - CX) / CX });
    if (it.bd) ev.push({ t: it.L, type: 'badgeoff', pan: (it.x - CX) / CX });
    ev.push({ t: it.L + it.d * 0.92, type: 'absorb', cat: it.cat, i: it.i });
  }
  ev.push({ t: K.freeze, type: 'freeze' });
  ev.push({ t: K.tick0, type: 'tick' });
  for (let k = 0; ; k++) { const tt = K.tick0 + BEAT * (k + 1); if (tt >= K.type0 - 0.01) break; ev.push({ t: tt, type: 'tick', soft: 1 }); }
  for (let k = 0; k < PROMPT.length; k++) ev.push({ t: K.type0 + k * S8, type: 'key' });
  ev.push({ t: K.press - 0.35, type: 'windup' });
  ev.push({ t: K.press, type: 'press' });
  ev.push({ t: K.press + 0.05, type: 'whip' });
  ev.push({ t: K.morph0, type: 'morph' });
  ev.push({ t: K.full, type: 'chord' });
  ev.push({ t: K.emit, type: 'emit' });
  K.rows.forEach((rt, i) => { ev.push({ t: rt, type: 'row', i }); ev.push({ t: rt + S16 * 2, type: 'check', i }); });
  ev.push({ t: K.split, type: 'split' });
  K.cards.forEach((ct, i) => ev.push({ t: ct, type: 'card', i }));
  ev.push({ t: K.cards[0] + 0.0, type: 'scribble', dur: 2.6 });
  ev.push({ t: K.cards[1], type: 'typing', dur: 2.4 });
  ev.push({ t: K.cards[3] + 1.5, type: 'check', i: 9 });
  ev.push({ t: K.flow, type: 'flow' });
  K.nodes.forEach((nt, i) => ev.push({ t: nt, type: 'node', i }));
  [K.away, K.away + S16, K.away + S16 * 2, K.away + S16 * 3, K.quiet].forEach((tt, i) => ev.push({ t: tt, type: 'retract', i }));
  ev.push({ t: K.quiet, type: 'quiet' });
  ev.push({ t: K.num, type: 'scramble', dur: S16 * 4 });
  [K.num + S16 * 2, K.num + S16 * 3, K.num + S16 * 4].forEach((tt, i) => ev.push({ t: tt, type: 'lock', i }));
  ev.push({ t: K.numLabel, type: 'label' });
  ev.push({ t: K.reveal, type: 'reveal' });
  ev.push({ t: K.collapse, type: 'collapse' });
  ev.push({ t: K.collapse + 0.45, type: 'crt' });
  ev.push({ t: K.word - 0.4, type: 'sweep' });
  ev.push({ t: K.word, type: 'final' });
  for (let k = 0; k < TAGLINE.length; k++) ev.push({ t: K.tag0 + k * TAG_STEP, type: 'key', soft: 1 });
  ev.push({ t: K.tagOut, type: 'retract', i: 9 });
  for (let k = 0; k < 6; k++) ev.push({ t: K.wordOut + k * S16, type: 'drop', i: k });
  ev.push({ t: K.squash, type: 'squash' });
  K.blinks.forEach(b => ev.push({ t: b, type: 'tick' }));
  ev.push({ t: K.off, type: 'crtoff' });
  for (const [id, t0] of Object.entries(VO)) ev.push({ t: t0, type: 'voice', id });
  ev.push({ t: 0, type: 'timeline', K, VO, BEAT });
  return ev.sort((a, b) => a.t - b.t);
}

// ───────────── readcheck: every text the viewer must read ─────────────
export function texts(t) {
  const out = [];
  const box = (x0, y0, x1, y1) => ({ x0, y0, x1, y1 });
  if (t >= K.type0 && t < K.press) out.push({ id: 'prompt', text: PROMPT, ...box(700, 500, 1240, 580) });
  if (t >= K.emit + 0.3 && t < K.split) {
    out.push({ id: 'win-h', text: `已整理 ${ITEMS.length} 项`, ...box(560, 340, 900, 380) });
    out.push({ id: 'win-tag', text: 'SORTED · SUMMARIZED · FIXED', pass: true, ...box(1000, 340, 1370, 380) });
    K.rows.forEach((rt, i) => { if (t >= rt + 0.05) { const r = rowRect(i); out.push({ id: 'row' + i, text: `${ROWS[i][0]} · ${COUNTS[i]} → ${ROWS[i][1]}`, ...box(r.x, r.y, r.x + r.w, r.y + r.h) }); } });
  }
  if (t >= K.split + 0.4 && t < K.flow) for (let i = 0; i < 4; i++) { const r = CARD(i); out.push({ id: 'card' + i, text: CARD_T[i][0], ...box(r.x, r.y, r.x + 200, r.y + 70) }); }
  if (t >= K.flow + 0.5 && t < K.away) for (let i = 0; i < 5; i++) { const r = NODE(i); out.push({ id: 'node' + i, text: NODE_T[i], ...box(r.x, r.y, r.x + r.w, r.y + r.h) }); }
  if (t >= K.num + 0.7 && t < K.reveal) out.push({ id: 'num', text: '700+', ...box(560, 300, 1360, 600) });
  if (t >= K.numLabel + 0.25 && t < K.reveal) out.push({ id: 'numlabel', text: '部视频，由 Claude 用代码生成', ...box(620, 650, 1300, 720) });
  if (t >= K.reveal + 0.6 && t < K.collapse) out.push({ id: 'src', text: 'film.js', pass: true, ...box(CW.x, CW.y, CW.x + CW.w, CW.y + CW.h) });
  if (t >= K.word + 0.2 && t < K.wordOut) out.push({ id: 'word', text: 'Claude', ...box(700, 260, 1220, 430) });
  if (t >= K.word + 0.7 && t < K.wordOut - S16 * 2) out.push({ id: 'by', text: 'AI ASSISTANT · BY ANTHROPIC', ...box(760, 430, 1160, 465) });
  if (t >= K.tag0 && t < K.tagOut) out.push({ id: 'tag', text: TAGLINE, ...box(700, 500, 1240, 580) });
  return out;
}
