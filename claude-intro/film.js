function drawMess(g, t) {
  const te = Math.min(t, K.freeze);
  const dim = t < K.freeze ? 1 : lerp(1, 0.42, ss(seg(t, K.freeze, K.push1)));
  const tremble = ss(seg(te, K.freeze - 1, K.freeze)) * (t < K.freeze ? 1 : 0);
  const f = Math.floor(t * 24);
  for (const it of ITEMS) {
    const ps = spawnPose(it, te); if (!ps) continue;
    if (t >= it.L + it.d) continue;
    let x = it.x + ps.dx, y = it.y + ps.dy, sc = ps.sc, rot = ps.rot, a = ps.a * dim;
    if (tremble > 0) { x += (hash(f * 1.3 + it.i * 7.1) - 0.5) * 4.8 * tremble; y += (hash(f * 2.7 + it.i * 3.3) - 0.5) * 4.8 * tremble; }
    let launched = false;
    if (t >= it.L) {
      launched = true;
      const fp = flightPos(it, t);
      x = fp.x; y = fp.y; sc *= lerp(1, 0.1, ei(fp.p)); rot *= 1 - fp.p;
      a = lerp(Math.max(a, 0.42), 1, clamp((t - it.L) * 8)) * (1 - seg(fp.p, 0.82, 1));
      const pts = [];
      for (let k = 9; k >= 0; k--) { const q = flightPos(it, Math.max(it.L, t - k * 0.03)); pts.push([q.x, q.y]); }
      E.trail(g, pts, { color: CATCOL[it.cat], width: 5, alpha: 0.75 * (1 - fp.p * 0.5) });
    }
    if (a <= 0.01) continue;
    g.save(); g.translate(x, y); g.rotate(rot); g.scale(sc, sc); g.globalAlpha = a;
    drawItem(g, it, te, !launched);
    g.restore();
  }
}
